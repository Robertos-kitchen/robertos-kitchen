  if nullif(a->>'id','') is null then
    insert into maint_tasks(name, kind, location, equipment, every_n, every_unit, next_due, by_who, notes, created_by)
    values (left(trim(a->>'name'),120), coalesce(nullif(a->>'kind',''),'other'), left(trim(coalesce(a->>'location','')),120), left(trim(coalesce(a->>'equipment','')),120),
      (a->>'every_n')::int, a->>'every_unit', (a->>'next_due')::date, left(trim(coalesce(a->>'by_who','')),120), left(trim(coalesce(a->>'notes','')),1000), s.name)
    returning id into v_id;
  else
    update maint_tasks set name = left(trim(a->>'name'),120), kind = coalesce(nullif(a->>'kind',''),'other'),
      location = left(trim(coalesce(a->>'location','')),120), equipment = left(trim(coalesce(a->>'equipment','')),120),
      every_n = (a->>'every_n')::int, every_unit = a->>'every_unit', next_due = (a->>'next_due')::date,
      by_who = left(trim(coalesce(a->>'by_who','')),120), notes = left(trim(coalesce(a->>'notes','')),1000)
    where id = (a->>'id')::uuid and active returning id into v_id;
    if v_id is null then raise exception 'no_task' using errcode = 'P0001'; end if;
  end if;
  perform maint_roll();
  return jsonb_build_object('id', v_id);
end $$;

create or replace function maint_task_done(p_emp text, p_id uuid, p_note text) returns jsonb
language plpgsql security definer set search_path to 'public' as $$
declare s staff; k maint_cards;
begin
  s := learn_who(p_emp);
  if not (maint_has(s.id,'technician') or maint_has(s.id,'chef')) then raise exception 'not_allowed' using errcode = 'P0001'; end if;
  select * into k from maint_cards where task_id = p_id and checked_at is null limit 1;
  if k.id is not null then raise exception 'has_card' using errcode = 'P0001'; end if;
  perform maint_task_did(p_id, maint_today(), s.name, nullif(trim(coalesce(p_note,'')),''), null);
  return jsonb_build_object('next_due', (select next_due from maint_tasks where id = p_id));
end $$;

create or replace function maint_task_remove(p_emp text, p_id uuid) returns void
language plpgsql security definer set search_path to 'public' as $$
declare s staff;
begin
  s := learn_who(p_emp);
  if not (maint_has(s.id,'technician') or maint_has(s.id,'chef')) then raise exception 'not_allowed' using errcode = 'P0001'; end if;
  update maint_tasks set active = false where id = p_id;
end $$;

