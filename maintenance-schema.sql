-- Kitchen Maintenance (Kitchen app) — Chef Andrea through Tell us, 25 Sep 2026 (inbox fe2b2456):
-- "Every fault, breakdown or maintenance issue reported in the kitchen must generate a job card",
-- plus a calendar of recurring maintenance (grease trap, hood & extraction, servicing, preventive).
-- Built to the mock-up Francesco approved on 25 Sep 2026 and his rules:
--   · every signature is a STAFF CODE (the employee ID, typed again at the moment of signing)
--   · the technician is Andrea Falcone for testing, until the new technician is hired; that is a
--     row in maint_people, not code
--   · the chef-in-charge check is Danilo or Antonio only (maint_people role 'chef'); a card is not
--     closed until one of them signs, and it cannot be the same person who signed as technician
--   · a new card alerts the technician by email and in the app (the Home badge); a completed card
--     emails the chefs for their check
--
-- Every table is RLS-on with NO policy; everything goes through the security-definer maint_*
-- functions. Sign-in is the employee ID, like Learning and Training (learn_who).
-- Emails are QUEUED by the database (maint_mail) and sent by the edge function maint-notify,
-- which the database calls itself through pg_net. The app never calls it, so the function
-- can only ever send a mail the database has already queued, to the people the database chose.
-- A card reported by a test person (staff name starting "zz") or for equipment starting "zz" is
-- a TEST card: its mails go to Francesco only, with [TEST] in the subject.
--
-- Kitchen database: zrpglswalgjbtghudmhu

create table if not exists maint_people (
  staff_id uuid not null,
  role text not null check (role in ('technician','chef')),
  email text not null,
  active boolean not null default true,
  primary key (staff_id, role)
);

create table if not exists maint_cards (
  id uuid primary key default gen_random_uuid(),
  card_no bigint generated by default as identity unique,
  is_test boolean not null default false,
  source text not null default 'report' check (source in ('report','calendar')),
  task_id uuid,
  reported_by_id uuid, reported_by text not null, reported_at timestamptz not null default now(),
  location text not null, equipment text not null, problem text not null,
  media jsonb not null default '[]'::jsonb,
  status text not null default 'new' check (status in ('new','acknowledged','in_progress','on_hold','completed')),
  read_at timestamptz, read_by text,
  tech_id uuid, tech_name text,
  started_at timestamptz, hold_at timestamptz, hold_reason text,
  diagnosis text, cause text, solution text, est_cost numeric(12,2), est_time text, parts text, notes text,
  assessed_at timestamptz, assessed_by text,
  work_done text, final_cost numeric(12,2), completed_at timestamptz,
  tech_signed_id uuid, tech_signed_by text,
  checked_at timestamptz, checked_id uuid, checked_by text,
  sent_back_at timestamptz, sent_back_by text, sent_back_note text,
  updated_at timestamptz not null default now()
);
create index if not exists maint_cards_open on maint_cards(checked_at, status);
create index if not exists maint_cards_task on maint_cards(task_id);

create table if not exists maint_tasks (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  kind text not null default 'other' check (kind in ('grease','hood','service','preventive','other')),
  location text not null default '', equipment text not null default '',
  every_n int not null check (every_n between 1 and 366),
  every_unit text not null check (every_unit in ('day','week','month')),
  next_due date not null,
  by_who text not null default '',
  notes text not null default '',
  active boolean not null default true,
  created_by text not null, created_at timestamptz not null default now()
);

create table if not exists maint_task_log (
  id uuid primary key default gen_random_uuid(),
  task_id uuid not null references maint_tasks(id) on delete cascade,
  done_on date not null, done_at timestamptz not null default now(),
  done_by text not null, note text, card_id uuid
);
create index if not exists maint_task_log_task on maint_task_log(task_id, done_on desc);

create table if not exists maint_mail (
  id bigint generated by default as identity primary key,
  card_id uuid not null references maint_cards(id) on delete cascade,
  kind text not null check (kind in ('new','check')),
  to_list text[] not null,
  is_test boolean not null default false,
  status text not null default 'queued' check (status in ('queued','sending','sent','failed')),
  tries int not null default 0,
  resend_id text, error text,
  created_at timestamptz not null default now(), sent_at timestamptz
);
create index if not exists maint_mail_status on maint_mail(status, created_at);

alter table maint_people   enable row level security;
alter table maint_cards    enable row level security;
alter table maint_tasks    enable row level security;
alter table maint_task_log enable row level security;
alter table maint_mail     enable row level security;
revoke all on maint_people, maint_cards, maint_tasks, maint_task_log, maint_mail from anon, authenticated;

