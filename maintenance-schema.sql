-- Opening a card as the technician is the moment it was READ: stamped once, and a New card
-- becomes Acknowledged with that technician on it.
create or replace function maint_read(p_emp text, p_id uuid) returns jsonb
language plpgsql security definer set search_path to 'public' as $$
declare s staff; c maint_cards;
begin
  s := learn_who(p_emp);
  if not maint_has(s.id,'technician') then return null; end if;
  update maint_cards set read_at = now(), read_by = s.name,
         tech_id = coalesce(tech_id, s.id), tech_name = coalesce(tech_name, s.name),
         status = case when status = 'new' then 'acknowledged' else status end, updated_at = now()
   where id = p_id and read_at is null returning * into c;
  return case when c.id is null then null else maint_card_row(c) end;
end $$;

create or replace function maint_report(p_emp text, p_location text, p_equipment text, p_problem text, p_media jsonb) returns jsonb
language plpgsql security definer set search_path to 'public' as $$
declare s staff; c maint_cards; m jsonb; v_media jsonb := '[]'::jsonb;
begin
  s := learn_who(p_emp);
  if length(trim(coalesce(p_location,''))) < 2 then raise exception 'no_location' using errcode = 'P0001'; end if;
  if length(trim(coalesce(p_equipment,''))) < 2 then raise exception 'no_equipment' using errcode = 'P0001'; end if;
  if length(trim(coalesce(p_problem,''))) < 3 then raise exception 'no_problem' using errcode = 'P0001'; end if;
  if jsonb_typeof(coalesce(p_media,'[]'::jsonb)) <> 'array' or jsonb_array_length(coalesce(p_media,'[]'::jsonb)) > 8 then raise exception 'bad_media' using errcode = 'P0001'; end if;
  for m in select * from jsonb_array_elements(coalesce(p_media,'[]'::jsonb)) loop
    if coalesce(m->>'path','') !~ '^c/[0-9a-f-]{36}/[A-Za-z0-9._-]+$'
       or not exists(select 1 from storage.objects o where o.bucket_id = 'maint-media' and o.name = m->>'path') then
      raise exception 'bad_media' using errcode = 'P0001'; end if;
    v_media := v_media || jsonb_build_array(jsonb_build_object('path', m->>'path',
      'kind', case when m->>'kind' = 'video' then 'video' else 'photo' end, 'size', coalesce((m->>'size')::bigint, 0)));
  end loop;
  insert into maint_cards(is_test, reported_by_id, reported_by, location, equipment, problem, media)
  values (s.name ~* '^zz' or trim(p_equipment) ~* '^zz', s.id, s.name, left(trim(p_location),120), left(trim(p_equipment),120), left(trim(p_problem),2000), v_media)
  returning * into c;
  perform maint_queue(c.id, 'new');
  return jsonb_build_object('id', c.id, 'card_no', c.card_no);
end $$;

create or replace function maint_amount(p text) returns numeric
language plpgsql immutable as $$
begin
  if p is null or trim(p) = '' then return null; end if;
  if trim(p) !~ '^\d{1,7}(\.\d{1,2})?$' then raise exception 'bad_amount' using errcode = 'P0001'; end if;
  return trim(p)::numeric;
end $$;

create or replace function maint_step(p_emp text, p_id uuid, p_op text, p_args jsonb) returns jsonb
language plpgsql security definer set search_path to 'public' as $$
declare s staff; c maint_cards; a jsonb := coalesce(p_args,'{}'::jsonb); v_tech boolean; v_chef boolean;
begin
  s := learn_who(p_emp);
  v_tech := maint_has(s.id,'technician'); v_chef := maint_has(s.id,'chef');
  select * into c from maint_cards where id = p_id for update;
  if c.id is null then raise exception 'no_card' using errcode = 'P0001'; end if;
  if c.checked_at is not null then raise exception 'closed' using errcode = 'P0001'; end if;

  if p_op in ('start','hold','resume','assess','complete') then
    if not v_tech then raise exception 'not_tech' using errcode = 'P0001'; end if;
    if c.status = 'completed' then raise exception 'completed' using errcode = 'P0001'; end if;
    -- anything the technician does is also the moment it was read
    update maint_cards set read_at = coalesce(read_at, now()), read_by = coalesce(read_by, s.name),
           tech_id = coalesce(tech_id, s.id), tech_name = coalesce(tech_name, s.name) where id = p_id;
  end if;

  if p_op = 'start' then
    update maint_cards set status = 'in_progress', started_at = coalesce(started_at, now()), hold_reason = null, updated_at = now() where id = p_id;
  elsif p_op = 'hold' then
    update maint_cards set status = 'on_hold', hold_at = now(), hold_reason = nullif(left(trim(coalesce(a->>'reason','')),200),''), updated_at = now() where id = p_id;
  elsif p_op = 'resume' then
    if c.status <> 'on_hold' then raise exception 'not_on_hold' using errcode = 'P0001'; end if;
    update maint_cards set status = 'in_progress', started_at = coalesce(started_at, now()), hold_reason = null, updated_at = now() where id = p_id;
  elsif p_op = 'assess' then
    update maint_cards set
      diagnosis = nullif(left(trim(coalesce(a->>'diagnosis','')),2000),''),
      cause     = nullif(left(trim(coalesce(a->>'cause','')),1000),''),
      solution  = nullif(left(trim(coalesce(a->>'solution','')),1000),''),
      est_cost  = maint_amount(a->>'est_cost'),
      est_time  = nullif(left(trim(coalesce(a->>'est_time','')),120),''),
      parts     = nullif(left(trim(coalesce(a->>'parts','')),1000),''),
      notes     = nullif(left(trim(coalesce(a->>'notes','')),2000),''),
      assessed_at = now(), assessed_by = s.name, updated_at = now()
    where id = p_id;
  elsif p_op = 'complete' then
    if trim(coalesce(a->>'code','')) <> trim(s.emp_id) then raise exception 'bad_code' using errcode = 'P0001'; end if;
    if length(trim(coalesce(a->>'work_done',''))) < 3 then raise exception 'no_work' using errcode = 'P0001'; end if;
    if maint_amount(a->>'final_cost') is null then raise exception 'no_cost' using errcode = 'P0001'; end if;
    update maint_cards set status = 'completed', work_done = left(trim(a->>'work_done'),2000), final_cost = maint_amount(a->>'final_cost'),
           completed_at = now(), tech_signed_id = s.id, tech_signed_by = s.name, hold_reason = null, updated_at = now()
     where id = p_id;
    perform maint_queue(p_id, 'check');
  elsif p_op = 'check' then
    if not v_chef then raise exception 'not_chef' using errcode = 'P0001'; end if;
    if c.status <> 'completed' then raise exception 'not_completed' using errcode = 'P0001'; end if;
    if trim(coalesce(a->>'code','')) <> trim(s.emp_id) then raise exception 'bad_code' using errcode = 'P0001'; end if;
    if c.tech_signed_id = s.id then raise exception 'same_person' using errcode = 'P0001'; end if;
    update maint_cards set checked_at = now(), checked_id = s.id, checked_by = s.name, updated_at = now() where id = p_id;
    -- a card the calendar opened closes its calendar job too, and the next date rolls on
    if c.task_id is not null then perform maint_task_did(c.task_id, (c.completed_at at time zone 'Asia/Dubai')::date, c.tech_signed_by, 'Job card JC-' || lpad(c.card_no::text, 4, '0'), c.id); end if;
  elsif p_op = 'send_back' then
    if not v_chef then raise exception 'not_chef' using errcode = 'P0001'; end if;
    if c.status <> 'completed' then raise exception 'not_completed' using errcode = 'P0001'; end if;
    if length(trim(coalesce(a->>'note',''))) < 3 then raise exception 'no_note' using errcode = 'P0001'; end if;
    update maint_cards set status = 'in_progress', completed_at = null, tech_signed_id = null, tech_signed_by = null,
           sent_back_at = now(), sent_back_by = s.name, sent_back_note = left(trim(a->>'note'),500), updated_at = now() where id = p_id;
  else
    raise exception 'bad_op' using errcode = 'P0001';
  end if;
  select * into c from maint_cards where id = p_id;
  return maint_card_row(c);
end $$;

-- For the Home tile: no sign-in, counts only.
create or replace function maint_summary() returns jsonb
language sql stable security definer set search_path to 'public' as $$
  select jsonb_build_object(
    'open',    (select count(*) from maint_cards where checked_at is null and not is_test),
    'new',     (select count(*) from maint_cards where status = 'new' and not is_test),
    'to_check',(select count(*) from maint_cards where status = 'completed' and checked_at is null and not is_test),
    'overdue', (select count(*) from maint_tasks where active and next_due < maint_today()))
$$;

-- ── calendar ──────────────────────────────────────────────────────────────
create or replace function maint_step_date(d date, n int, u text) returns date
language sql immutable as $$
  select (d + case u when 'day' then make_interval(days => n) when 'week' then make_interval(weeks => n) else make_interval(months => n) end)::date
$$;

create or replace function maint_task_did(p_task uuid, p_on date, p_by text, p_note text, p_card uuid) returns void
language plpgsql security definer set search_path to 'public' as $$
declare t maint_tasks;
begin
  select * into t from maint_tasks where id = p_task for update;
  if t.id is null then return; end if;
  insert into maint_task_log(task_id, done_on, done_by, note, card_id) values (p_task, p_on, p_by, p_note, p_card);
  update maint_tasks set next_due = maint_step_date(p_on, every_n, every_unit) where id = p_task;
end $$;

-- A calendar job past its date opens a job card on its own — once, while that card is open.
create or replace function maint_roll() returns int
language plpgsql security definer set search_path to 'public' as $$
declare t maint_tasks; c maint_cards; n int := 0;
begin
  for t in select * from maint_tasks x where x.active and x.next_due < maint_today()
             and not exists(select 1 from maint_cards k where k.task_id = x.id and k.checked_at is null) loop
    insert into maint_cards(source, task_id, is_test, reported_by, location, equipment, problem)
    values ('calendar', t.id, t.name ~* '^zz' or t.equipment ~* '^zz', 'Maintenance calendar',
      coalesce(nullif(t.location,''),'Kitchen'), coalesce(nullif(t.equipment,''), t.name),
      t.name || ' was due ' || to_char(t.next_due, 'FMDD Mon YYYY') || ' (every ' || t.every_n || ' ' || t.every_unit || case when t.every_n > 1 then 's' else '' end || ')' ||
      case when t.by_who <> '' then '. Done by: ' || t.by_who else '' end || case when t.notes <> '' then '. ' || t.notes else '' end)
    returning * into c;
    perform maint_queue(c.id, 'new');
    n := n + 1;
  end loop;
  return n;
end $$;

